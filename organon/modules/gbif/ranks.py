# GBIF kingdom -> Organon domain; alias of the table shared with ITIS,
# WoRMS and IRMNG (`core.domains.KINGDOM_MAP`).
from organon.core.domains import KINGDOM_MAP as _SHARED_KINGDOM_MAP  # noqa: E402


def gbif_lookup_kingdom(kingdom: str) -> str:
    """Return the Organon domain of a GBIF kingdom."""
    return _SHARED_KINGDOM_MAP.get(kingdom, "neutre")


def gbif_to_wp_rank(rank: str) -> str | None:
    """Return the Wikipedia rank of a GBIF rank, or None."""
    return GBIF_WP.get(rank)


def gbif_marker_to_rank(marker: str) -> str | None:
    """Return the GBIF rank of an abbreviated marker, or None."""
    return GBIF_MARKERS.get(marker)
